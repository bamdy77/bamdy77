  await query(`ALTER TABLE sms_staff_contacts ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id) ON DELETE CASCADE;`);
  await query(`
    DO $$ BEGIN
      ALTER TABLE sms_staff_contacts ADD CONSTRAINT sms_staff_contacts_user_id_key UNIQUE (user_id);
    EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
    END $$;
  `);
